function translateText(value: string, language: AdminLanguage) {
  if (language === "uz") return value;
  const leading = value.match(/^\s*/)?.[0] || "";
  const trailing = value.match(/\s*$/)?.[0] || "";
  const core = value.trim();
  const normalizedCore = core.replace(/[‘’ʻʼ`]/g, "'");
  const exact = dictionary[core] || dictionary[normalizedCore];
  if (exact) return `${leading}${exact[language]}${trailing}`;

  const entity = localizeEntityName(core, language);
  if (entity !== core) return `${leading}${entity}${trailing}`;

  const looksLikePersonName = core.split(/\s+/).length >= 2
    && core.split(/\s+/).length <= 6
    && /(?:o['‘’]g['‘’]li|qizi|ovich|ovna|ov|ova|yev|yeva|ev|eva)$/i.test(core);
  if (looksLikePersonName) {
    return `${leading}${localizePersonName(core, language)}${trailing}`;
  }

  const replacements: Array<[RegExp, (match: RegExpMatchArray) => string]> = [
    [/^(\d+) ta o'qituvchi$/, (m) => language === "ru" ? `${m[1]} преподавателей` : `${m[1]} teachers`],
    [/^(\d+) ta yuklama$/, (m) => language === "ru" ? `Нагрузок: ${m[1]}` : `${m[1]} workloads`],
    [/^(\d+) ta fan$/, (m) => language === "ru" ? `${m[1]} дисциплин` : `${m[1]} subjects`],
    [/^(\d+) ta biriktirma$/, (m) => language === "ru" ? `${m[1]} назначений` : `${m[1]} assignments`],
    [/^(\d+) ta topildi$/, (m) => language === "ru" ? `Найдено: ${m[1]}` : `${m[1]} found`],
    [/^(\d+)\s*fak\.$/, (m) => language === "ru" ? `${m[1]} фак.` : `${m[1]} fac.`],
    [/^(\d+(?:[.,]\d+)?)\s*stavka$/, (m) => language === "ru" ? `${m[1]} ${m[1] === "1" ? "ставка" : "ставки"}` : `${m[1]} rate`],
    [/^(\d[\d\s.,]*)\s*soat$/, (m) => language === "ru" ? `${m[1]} часов` : `${m[1]} hours`],
    [/^Yangi:\s*(\d+) ta$/, (m) => language === "ru" ? `Новые: ${m[1]}` : `New: ${m[1]}`],
    [/^Mavjud:\s*(\d+) ta$/, (m) => language === "ru" ? `Готовые: ${m[1]}` : `Existing: ${m[1]}`],
    [/^Jami:\s*(\d+) ta o'qituvchi$/, (m) => language === "ru" ? `Всего: ${m[1]} преподавателей` : `Total: ${m[1]} teachers`],
    [/^Barcha DL\/MD biriktmalar\. Umumiy:\s*(.+)\s*soat$/, (m) => language === "ru" ? `Все назначения ДП/МД. Всего: ${m[1]} часов` : `All DP/MD assignments. Total: ${m[1]} hours`],
    [/^Jami:\s*(.+)\s+soat$/, (m) => language === "ru" ? `Итого: ${m[1]} часов` : `Total: ${m[1]} hours`],
    [/^Jami\s+(.+)$/, (m) => language === "ru" ? `Всего ${m[1]}` : `Total ${m[1]}`],
    [/^(\d+)-semestr$/, (m) => language === "ru" ? `${m[1]}-й семестр` : `Semester ${m[1]}`],
  ];
  for (const [pattern, replacer] of replacements) {
    const match = normalizedCore.match(pattern);
    if (match) return `${leading}${replacer(match)}${trailing}`;
  }
  return value;
}

export function AdminTranslationLayer({ children, language }: { children: ReactNode; language: AdminLanguage }) {
  const rootRef = useRef<HTMLDivElement>(null);
  const textOriginalsRef = useRef(new Map<Text, { original: string; rendered: string }>());
  const attributeOriginalsRef = useRef(new Map<Element, Map<string, { original: string; rendered: string }>>());

  useEffect(() => {
    if (!rootRef.current) return;
    const root = document.body;
    const textOriginals = textOriginalsRef.current;
    const attributeOriginals = attributeOriginalsRef.current;
    const attributes = ["placeholder", "title", "aria-label"];

    const apply = (target: Node) => {
      const walker = document.createTreeWalker(target, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT);
      const nodes: Node[] = [target];
      while (walker.nextNode()) nodes.push(walker.currentNode);
      for (const node of nodes) {
        if (node.nodeType === Node.TEXT_NODE) {
          const textNode = node as Text;
          let state = textOriginals.get(textNode);
          if (!state || textNode.data !== state.rendered) {
            state = { original: textNode.data, rendered: textNode.data };
          }
          const original = state.original;
          const translated = translateText(original, language);
          if (translated !== original || textOriginals.has(textNode)) {
            state.rendered = translated;
            textOriginals.set(textNode, state);
            if (textNode.data !== translated) textNode.data = translated;
          }
          continue;
        }
        if (!(node instanceof Element)) continue;
        for (const attribute of attributes) {
          const current = node.getAttribute(attribute);
          if (!current) continue;
          let originals = attributeOriginals.get(node);
          if (!originals) {
            originals = new Map<string, { original: string; rendered: string }>();
            attributeOriginals.set(node, originals);
          }
          let state = originals.get(attribute);
          if (!state || current !== state.rendered) {
            state = { original: current, rendered: current };
          }
          const original = state.original;
          const translated = translateText(original, language);
          if (translated !== original || originals.has(attribute)) {
            state.rendered = translated;
            originals.set(attribute, state);
            if (current !== translated) node.setAttribute(attribute, translated);
          }
        }
      }
    };

    apply(root);
    const observer = new MutationObserver((mutations) => {
      for (const mutation of mutations) {
        if (mutation.type === "characterData" || mutation.type === "attributes") apply(mutation.target);
        mutation.addedNodes.forEach(apply);
      }
    });
    observer.observe(root, {
      childList: true,
      subtree: true,
      characterData: true,
      attributes: true,
      attributeFilter: attributes,
    });
    return () => observer.disconnect();
  }, [language]);

  return <div ref={rootRef} className="contents">{children}</div>;
}
